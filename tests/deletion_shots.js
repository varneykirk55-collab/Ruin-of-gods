const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');
const out = '/opt/cursor/artifacts';
fs.mkdirSync(out, { recursive: true });
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  ok   ' + m); } else { fail++; console.log('  FAIL ' + m); } };
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: out, size: { width: 1280, height: 720 } } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push(e.message));
  await p.goto('file://' + path.resolve(__dirname, '../index.html'));
  await p.waitForFunction(() => window.__game && !document.getElementById('begin').disabled, null, { timeout: 30000 });
  await p.evaluate(() => { __game.newWorld(1234); __game.world.rainT = 1e9; __game.world.time = 0.42; __game.setInt(0.72); });
  await p.click('#begin');
  await p.waitForTimeout(350);
  const ev = (f, arg) => arg === undefined ? p.evaluate(f) : p.evaluate(f, arg);
  const scr = (x, z) => ev(([x, z]) => { const q = __game.R.project(x, __game.world.hAt(x, z) + 0.3, z); return [(q[0] + 1) / 2 * innerWidth, (1 - q[1]) / 2 * innerHeight]; }, [x, z]);
  const cam = o => ev(o => { const c = __game.R.cam; for (const k in o) { c[k] = o[k]; c['g' + k] = o[k]; } }, o);
  const shot = name => p.screenshot({ path: path.join(out, name) });
  const meadow = await ev(() => {
    const w = __game.world;
    for (let z = 70; z < 130; z++) for (let x = 20; x < 130; x++) {
      const i = z * 160 + x;
      if (w.tree[i] || w.bmap[i] || w.kind[i] === 5 || (w.flag[i] & 2) || !w.canEraseLand(i)) continue;
      if (Math.hypot(x - w.vc.x, z - w.vc.z) < 18) continue;
      return [x, z];
    }
    return [40, 90];
  });
  await p.keyboard.press('9');
  ok(await ev(() => __game.tool === 'delete'), 'deletion tool selected');
  await cam({ tx: meadow[0], tz: meadow[1], dist: 36, pitch: 1.05, yaw: 0.4 });
  await p.waitForTimeout(300);
  const a = await scr(meadow[0], meadow[1]);
  await p.mouse.move(a[0], a[1]);
  await p.waitForTimeout(250);
  const brush = await ev(() => { const w = __game.world; return { mark: __game.R.mark[2], radius: w.eraseRadius(0.72), brush: __game.R.brush, alpha: __game.R.markC[3] }; });
  console.log('  brush', brush);
  ok(Math.abs(brush.mark - brush.radius) < 0.05 && brush.brush === 1 && brush.alpha > 0.9, 'ground brush matches the erase radius');
  await shot('ability_deletion_brush.png');
  const house = await ev(() => { const b = __game.world.buildings.find(b => !b.gone && !b.ruin && b.type === 'house'); return [b.x, b.z, b.id]; });
  await cam({ tx: house[0], tz: house[1], dist: 24, pitch: 1.08, yaw: 0.45 });
  await p.waitForTimeout(280);
  const hs = await scr(house[0], house[1]);
  await p.mouse.move(hs[0], hs[1]);
  await p.waitForTimeout(280);
  const hover = await ev(() => { const h = __game.delHover; return h ? h.kind : ''; });
  ok(hover === 'b', 'house under the cursor is highlighted (' + hover + ')');
  await shot('ability_deletion_hover.png');
  await ev(() => __game.setSpeed(0));
  await p.mouse.click(hs[0], hs[1]);
  await p.waitForTimeout(120);
  await shot('ability_deletion.png');
  const pit = await ev(id => { const b = __game.world.buildings[id], i = __game.world.ci(b.x, b.z); return { gone: b.gone, h: __game.world.h[i], fades: __game.world.fades.length }; }, house[2]);
  ok(pit.gone && pit.h === -7 && pit.fades > 0, 'click cut a void and left a dissolve (' + pit.fades + ' fades, h ' + pit.h + ')');
  await ev(() => __game.setSpeed(1));
  const trench = await ev(() => {
    const w = __game.world, z = 96, x = Math.round(w.rx(z)) + 3;
    return [x, z, Math.round(w.rx(z)) + 14, z + 2];
  });
  await cam({ tx: (trench[0] + trench[2]) / 2, tz: trench[1], dist: 42, pitch: 1.08, yaw: 0.3 });
  await p.waitForTimeout(250);
  const t0 = await scr(trench[0], trench[1]), t1 = await scr(trench[2], trench[3]);
  console.log('  trench screen', t0.map(v => v.toFixed(0)), t1.map(v => v.toFixed(0)));
  await p.mouse.move(t0[0], t0[1]);
  await p.mouse.down();
  await p.mouse.move(t1[0], t1[1], { steps: 10 });
  await p.mouse.up();
  await ev(() => { const w = __game.world; for (let i = 0; i < 12 * 60; i++) w.tick(1 / 60); });
  await ev(() => __game.world.decayFades(2));
  await cam({ tx: (trench[0] + trench[2]) / 2, tz: trench[1] + 1, dist: 34, pitch: 1.02, yaw: 0.2 });
  await p.waitForTimeout(300);
  const wet = await ev(t => { const w = __game.world, i = w.ci((t[0] + t[2]) / 2, t[1]); return { h: w.h[i], water: w.w[i] }; }, trench);
  console.log('  trench state', wet);
  ok(wet.h < -5, 'drag left a trench');
  await shot('ability_deletion_trench.png');
  console.log(errs.length ? 'page errors ' + errs.join(' | ') : 'no page errors');
  console.log(pass + ' passed, ' + fail + ' failed');
  const video = p.video();
  await ctx.close(); await b.close();
  if (video) { const vp = await video.path(); fs.copyFileSync(vp, path.join(out, 'deletion_land.webm')); console.log('video', path.join(out, 'deletion_land.webm')); }
  process.exit(fail ? 1 : 0);
})().catch(e => { console.log('ERR', e.stack || e); process.exit(1); });